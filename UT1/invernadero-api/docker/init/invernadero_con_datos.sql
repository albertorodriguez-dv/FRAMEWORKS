DROP DATABASE IF EXISTS invernadero;
CREATE DATABASE invernadero CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE invernadero;

-- ---------------------------------------------------------------------
--  PERFILES DE USUARIO
-- ---------------------------------------------------------------------
CREATE TABLE roles (
  id_rol      INT          NOT NULL AUTO_INCREMENT,
  nombre      VARCHAR(20)  NOT NULL,  -- ADMIN, TECNICO o INVITADO
  descripcion VARCHAR(150) NOT NULL,
  PRIMARY KEY (id_rol),
  UNIQUE KEY uq_roles_nombre (nombre)
) ENGINE=InnoDB;  -- Perfiles de usuario del sistema

CREATE TABLE usuarios (
  id_usuario INT          NOT NULL AUTO_INCREMENT,
  email      VARCHAR(100) NOT NULL,
  nombre     VARCHAR(80)  NOT NULL,
  password   VARCHAR(100) NOT NULL,  -- Se guarda tal cual llega (texto plano) a proposito: se migra a bcrypt en la S10
  id_rol     INT          NOT NULL,
  creado_el  DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id_usuario),
  UNIQUE KEY uq_usuarios_email (email),
  CONSTRAINT fk_usuarios_rol FOREIGN KEY (id_rol) REFERENCES roles (id_rol)
) ENGINE=InnoDB;  -- Personas que acceden al sistema (cada una con un unico perfil)

-- ---------------------------------------------------------------------
--  CATALOGO DE CULTIVOS Y ZONAS DEL INVERNADERO
-- ---------------------------------------------------------------------
CREATE TABLE cultivos (
  id_cultivo        INT          NOT NULL AUTO_INCREMENT,
  nombre            VARCHAR(50)  NOT NULL,
  temperatura_min   DECIMAL(4,1) NOT NULL,  -- Temperatura ambiente minima recomendada (C)
  temperatura_max   DECIMAL(4,1) NOT NULL,  -- Temperatura ambiente maxima recomendada (C)
  humedad_suelo_min DECIMAL(4,1) NOT NULL,  -- Por debajo de este % el suelo esta demasiado seco para la planta
  humedad_suelo_max DECIMAL(4,1) NOT NULL,  -- Por encima de este % el suelo ya esta suficientemente humedo
  PRIMARY KEY (id_cultivo),
  UNIQUE KEY uq_cultivos_nombre (nombre),
  CONSTRAINT ck_cultivos_temperatura CHECK (temperatura_min < temperatura_max),
  CONSTRAINT ck_cultivos_humedad CHECK (humedad_suelo_min < humedad_suelo_max)
) ENGINE=InnoDB;  -- Rangos ideales de cada tipo de planta

CREATE TABLE zonas (
  codigo_zona   VARCHAR(10)  NOT NULL,  -- Codigo corto, p. ej. Z01
  nombre        VARCHAR(60)  NOT NULL,
  id_cultivo    INT          NOT NULL,
  superficie_m2 DECIMAL(6,1) NOT NULL,
  caudal_l_min  DECIMAL(5,2) NOT NULL,  -- Litros por minuto que salen con la valvula de riego abierta
  PRIMARY KEY (codigo_zona),
  CONSTRAINT fk_zonas_cultivo FOREIGN KEY (id_cultivo) REFERENCES cultivos (id_cultivo)
) ENGINE=InnoDB;  -- Sectores del invernadero; cada uno tiene sus sensores y su valvula de riego

-- Historial de umbrales de riego de cada zona: solo se INSERTA (nunca se
-- actualiza); el umbral vigente es el ultimo registro de la zona.
CREATE TABLE umbrales_riego (
  id               INT          NOT NULL AUTO_INCREMENT,
  codigo_zona      VARCHAR(10)  NOT NULL,
  humedad_seca     DECIMAL(4,1) NOT NULL,  -- Si la humedad del suelo baja de este % se empieza a regar
  humedad_objetivo DECIMAL(4,1) NOT NULL,  -- Se riega hasta alcanzar este % de humedad
  fecha_hora       DATETIME     NOT NULL,
  id_usuario       INT          NULL,  -- Quien hizo el cambio; NULL = valores iniciales del sistema
  PRIMARY KEY (id),
  KEY ix_umbrales_zona (codigo_zona, id),
  CONSTRAINT fk_umbrales_zona FOREIGN KEY (codigo_zona) REFERENCES zonas (codigo_zona),
  CONSTRAINT fk_umbrales_usuario FOREIGN KEY (id_usuario) REFERENCES usuarios (id_usuario),
  CONSTRAINT ck_umbrales_rango CHECK (humedad_seca < humedad_objetivo)
) ENGINE=InnoDB;  -- Historial de umbrales de humedad que disparan y detienen el riego

-- ---------------------------------------------------------------------
--  MEDIDAS DE LOS SENSORES (una fila por zona cada 5 minutos)
-- ---------------------------------------------------------------------
-- Fecha y hora van en columnas SEPARADAS a proposito (los dispositivos
-- IoT suelen registrarlas asi): en la S8 se anade una columna fecha_hora
-- con una migracion incremental y se rellena a partir de ellas.
CREATE TABLE lecturas (
  id            INT          NOT NULL AUTO_INCREMENT,
  codigo_zona   VARCHAR(10)  NOT NULL,
  fecha         DATE         NOT NULL,
  hora          TIME         NOT NULL,
  temperatura_c DECIMAL(4,1) NULL,  -- Temperatura del aire (C); NULL si el sensor fallo en esa lectura
  humedad_suelo DECIMAL(4,1) NULL,  -- Humedad del suelo (%); a menor valor, mas seca esta la tierra; NULL si el sensor fallo
  litros        DECIMAL(6,2) NOT NULL DEFAULT 0,  -- Litros de agua gastados en los 5 minutos anteriores a esta lectura (caudalimetro)
  PRIMARY KEY (id),
  UNIQUE KEY uq_lecturas_zona_momento (codigo_zona, fecha, hora),
  CONSTRAINT fk_lecturas_zona FOREIGN KEY (codigo_zona) REFERENCES zonas (codigo_zona)
) ENGINE=InnoDB;  -- Lecturas de temperatura, humedad del suelo y consumo de agua

-- ---------------------------------------------------------------------
--  EVENTOS DE RIEGO
-- ---------------------------------------------------------------------
-- Una fila por cada cambio de estado de la valvula de una zona. Para saber
-- cuanto tiempo ha estado regando hay que emparejar cada ABIERTA con la
-- CERRADA siguiente (es el calculo del informe de la S9).
CREATE TABLE estados_valvula (
  id          INT          NOT NULL AUTO_INCREMENT,
  codigo_zona VARCHAR(10)  NOT NULL,
  estado      ENUM('ABIERTA','CERRADA')    NOT NULL,
  fecha       DATE         NOT NULL,
  hora        TIME         NOT NULL,
  motivo      ENUM('AUTOMATICO','MANUAL')  NOT NULL DEFAULT 'AUTOMATICO',  -- AUTOMATICO = lo decide el umbral de humedad; MANUAL = lo acciona una persona
  id_usuario  INT          NULL,  -- Quien lo acciono si el motivo es MANUAL
  PRIMARY KEY (id),
  KEY ix_valvula_zona_momento (codigo_zona, fecha, hora),
  CONSTRAINT fk_valvula_zona FOREIGN KEY (codigo_zona) REFERENCES zonas (codigo_zona),
  CONSTRAINT fk_valvula_usuario FOREIGN KEY (id_usuario) REFERENCES usuarios (id_usuario)
) ENGINE=InnoDB;  -- Aperturas y cierres de la valvula de riego de cada zona

-- Estado GLOBAL de la bomba de agua: no depende de ninguna zona (no tiene
-- clave ajena). Esta ON mientras haya al menos una valvula abierta.
CREATE TABLE estados_bomba (
  id     INT         NOT NULL AUTO_INCREMENT,
  estado ENUM('ON','OFF') NOT NULL,
  fecha  DATE        NOT NULL,
  hora   TIME        NOT NULL,
  PRIMARY KEY (id),
  KEY ix_bomba_momento (fecha, hora)
) ENGINE=InnoDB;  -- Encendidos y apagados de la bomba general del invernadero

